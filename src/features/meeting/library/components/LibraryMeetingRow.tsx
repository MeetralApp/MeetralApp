import type { MeetingRecord } from "../lib/meetingTypes";
import {
  formatLanguagePair,
  formatMeetingDate,
} from "../lib/meetingTypes";
import { isAutoGeneratedMeetingTitle, meetingChipDisplayTitle } from "../lib/meetingDisplay";
import AppTooltip from "@/shared/components/AppTooltip";
import { Badge } from "@/shared/ui/badge";
import { cn } from "@/shared/lib/utils";

interface Props {
  meeting: MeetingRecord;
  depth?: number;
  pinned?: boolean;
  onSelect: () => void;
}

export default function LibraryMeetingRow({
  meeting,
  depth = 0,
  pinned = false,
  onSelect,
}: Props) {
  const isLive = meeting.status === "live";
  const displayTitle = meetingChipDisplayTitle(meeting);
  const isAutoTitle = isAutoGeneratedMeetingTitle(meeting.title);
  const indent = depth > 0 ? 8 + depth * 16 : 0;

  return (
    <div
      className={cn(
        "mb-0.5 flex min-h-11 w-full min-w-0 items-stretch",
        pinned && "mb-1.5",
      )}
      style={indent > 0 ? { paddingLeft: indent } : undefined}
    >
      <AppTooltip label={meeting.title} side="right">
        <button
          type="button"
          className={cn(
            "min-w-0 flex-1 overflow-hidden cursor-pointer rounded-lg border border-transparent bg-transparent p-1.5 px-2 text-left font-[inherit] text-inherit",
            "hover:bg-hover-surface focus-visible:bg-hover-surface focus-visible:outline-none",
            isLive && "bg-[rgba(52,168,83,0.06)]",
            pinned && isLive && "border-[rgba(52,168,83,0.45)]",
          )}
          onClick={onSelect}
        >
          <span className="flex min-w-0 items-center gap-1.5 overflow-hidden">
            {isLive && (
              <span
                className="size-2 shrink-0 animate-pulse rounded-full bg-success"
                aria-hidden="true"
              />
            )}
            <span className="block min-w-0 flex-1 truncate text-sm font-semibold">
              {displayTitle}
            </span>
            {isLive && (
              <Badge
                variant="outline"
                className="shrink-0 border-[rgba(52,168,83,0.45)] bg-[rgba(52,168,83,0.12)] px-1.5 py-0 text-[0.65rem] text-success"
              >
                LIVE
              </Badge>
            )}
          </span>
          <span className="mt-0.5 block min-w-0 truncate text-[0.72rem] text-muted-foreground">
            {pinned && isLive ? (
              <>Current session · Return to live</>
            ) : (
              <>
                {!isAutoTitle && (
                  <>
                    {formatMeetingDate(meeting.startedAtMs)}
                    {" · "}
                  </>
                )}
                {formatLanguagePair(meeting.myLanguage, meeting.meetingLanguage)}
              </>
            )}
            {meeting.sessionMode === "notes" && " · Notes"}
            {meeting.hasSummary && !isLive && " · Summary"}
          </span>
        </button>
      </AppTooltip>
    </div>
  );
}
