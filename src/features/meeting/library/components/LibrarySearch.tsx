import {
  useEffect,
  useMemo,
  useRef,
  useState,
  type KeyboardEvent,
  type ReactNode,
} from "react";
import { Search, X } from "lucide-react";

import { searchMeetings } from "../lib/meetingApi";
import { splitHighlightParts } from "../lib/highlightSnippet";
import {
  formatLanguagePair,
  formatMeetingDate,
  type MeetingRecord,
  type MeetingSearchHit,
} from "../lib/meetingTypes";
import {
  isAutoGeneratedMeetingTitle,
  meetingChipDisplayTitle,
} from "../lib/meetingDisplay";
import { formatSegmentTimestamp } from "@/features/meeting/detail/lib/timelineTranscript";
import SectionHeading from "@/shared/components/SectionHeading";
import AppTooltip from "@/shared/components/AppTooltip";
import { Button } from "@/shared/ui/button";
import { Input } from "@/shared/ui/input";
import { cn } from "@/shared/lib/utils";
import { pipelineToolbarClasses } from "@/features/pipeline/lib/pipelineColors";

const DEBOUNCE_MS = 280;

const floatingSearchShellClass = cn(
  "flex h-9 items-stretch overflow-hidden rounded-lg border border-border/80",
  "bg-secondary shadow-[var(--pane-elevated)] ring-1 ring-foreground/10",
);

interface Props {
  /** History drawer open. */
  drawerOpen?: boolean;
  /** Floating search field open (toggle). */
  searchOpen: boolean;
  onSearchOpenChange: (open: boolean) => void;
  meetings: MeetingRecord[];
  onSelectHit: (hit: MeetingSearchHit) => void;
  /** True when query is non-empty — parent hides browse tree. */
  onActiveChange?: (active: boolean) => void;
  /** Browse tree (Current / Recent / Folders). Hidden while search has a query. */
  children: ReactNode;
  /** Right of the search toggle — typically New meeting. */
  footerAction: ReactNode;
}

function HighlightedSnippet({
  text,
  query,
}: {
  text: string;
  query: string;
}) {
  const parts = splitHighlightParts(text, query);
  return (
    <span className="line-clamp-2 text-[11px] leading-snug text-muted-foreground">
      {parts.map((part, i) =>
        part.match ? (
          <mark
            key={i}
            className="rounded-sm bg-accent/40 px-0.5 text-foreground"
          >
            {part.text}
          </mark>
        ) : (
          <span key={i}>{part.text}</span>
        ),
      )}
    </span>
  );
}

function hitDisplayTitle(
  hit: MeetingSearchHit,
  meeting: MeetingRecord | undefined,
): string {
  if (meeting) {
    return meetingChipDisplayTitle(meeting);
  }
  return hit.title;
}

function hitMetaLine(meeting: MeetingRecord | undefined): string | null {
  if (!meeting) return null;
  const parts: string[] = [];
  if (!isAutoGeneratedMeetingTitle(meeting.title)) {
    parts.push(formatMeetingDate(meeting.startedAtMs));
  }
  parts.push(formatLanguagePair(meeting.myLanguage, meeting.meetingLanguage));
  return parts.join(" · ");
}

export default function LibrarySearch({
  drawerOpen = true,
  searchOpen,
  onSearchOpenChange,
  meetings,
  onSelectHit,
  onActiveChange,
  children,
  footerAction,
}: Props) {
  const [query, setQuery] = useState("");
  const [hits, setHits] = useState<MeetingSearchHit[]>([]);
  const [searching, setSearching] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const inputRef = useRef<HTMLInputElement>(null);

  const trimmed = query.trim();
  const active = drawerOpen && searchOpen && trimmed.length > 0;

  const meetingsById = useMemo(() => {
    const map = new Map<string, MeetingRecord>();
    for (const m of meetings) map.set(m.id, m);
    return map;
  }, [meetings]);

  const closeSearch = () => {
    setQuery("");
    setHits([]);
    setSearching(false);
    setError(null);
    onSearchOpenChange(false);
  };

  useEffect(() => {
    if (!drawerOpen) {
      setQuery("");
      setHits([]);
      setSearching(false);
      setError(null);
    }
  }, [drawerOpen]);

  useEffect(() => {
    if (!searchOpen) {
      setQuery("");
      setHits([]);
      setSearching(false);
      setError(null);
      return;
    }
    const id = window.requestAnimationFrame(() => {
      inputRef.current?.focus();
    });
    return () => window.cancelAnimationFrame(id);
  }, [searchOpen]);

  useEffect(() => {
    onActiveChange?.(active);
  }, [active, onActiveChange]);

  useEffect(() => {
    if (!active) {
      setHits([]);
      setSearching(false);
      setError(null);
      return;
    }

    let cancelled = false;
    setSearching(true);
    const timer = window.setTimeout(() => {
      void searchMeetings({ query: trimmed, limit: 20 })
        .then((results) => {
          if (cancelled) return;
          setHits(results);
          setError(null);
        })
        .catch((err: unknown) => {
          if (cancelled) return;
          setHits([]);
          setError(err instanceof Error ? err.message : String(err));
        })
        .finally(() => {
          if (!cancelled) setSearching(false);
        });
    }, DEBOUNCE_MS);

    return () => {
      cancelled = true;
      window.clearTimeout(timer);
    };
  }, [active, trimmed]);

  const statusLine = (() => {
    if (!active) return null;
    if (error) return null;
    if (searching && hits.length === 0) return "Searching…";
    if (!searching && hits.length === 0) return null;
    const n = hits.length;
    return n === 1 ? "1 match in transcripts" : `${n} matches in transcripts`;
  })();

  const onKeyDown = (event: KeyboardEvent<HTMLInputElement>) => {
    if (event.key === "Escape") {
      event.preventDefault();
      closeSearch();
    }
  };

  return (
    <div className="flex min-h-0 flex-1 flex-col">
      <div
        className={cn(
          "flex min-h-0 flex-1 flex-col overflow-hidden",
          active ? "pb-2" : null,
        )}
      >
        {active ? (
          <div className="flex min-h-0 flex-1 flex-col gap-1.5">
            {statusLine ? (
              <p className="m-0 shrink-0 px-0.5 text-[11px] text-muted-foreground">
                {statusLine}
              </p>
            ) : null}
            {error ? (
              <p
                className="m-0 shrink-0 px-0.5 text-xs text-destructive"
                role="alert"
              >
                {error}
              </p>
            ) : null}

            <div className="min-h-0 flex-1 overflow-y-auto">
              {searching && hits.length === 0 ? null : error ? null : hits.length === 0 ? (
                <p className="m-0 px-0.5 py-2 text-sm text-muted-foreground">
                  No matches for &ldquo;{trimmed}&rdquo;
                </p>
              ) : (
                <>
                  <SectionHeading as="h3" className="mb-1 px-0.5">
                    Results
                  </SectionHeading>
                  <ul className="pb-1">
                    {hits.map((hit) => {
                      const meeting = meetingsById.get(hit.meetingId);
                      const title = hitDisplayTitle(hit, meeting);
                      const meta = hitMetaLine(meeting);
                      const segmentTime =
                        hit.startedAtMs != null
                          ? formatSegmentTimestamp(hit.startedAtMs)
                          : null;

                      return (
                        <li key={`${hit.meetingId}:${hit.bestSegmentId}`}>
                          <button
                            type="button"
                            className={cn(
                              "mb-0.5 flex w-full cursor-pointer flex-col gap-0.5 rounded-lg border border-transparent px-2 py-1.5 text-left",
                              "hover:bg-hover-surface focus-visible:bg-hover-surface focus-visible:outline-none",
                            )}
                            onClick={() => onSelectHit(hit)}
                          >
                            <span className="truncate text-sm font-semibold text-foreground">
                              {title}
                            </span>
                            {meta ? (
                              <span className="truncate text-[0.72rem] text-muted-foreground">
                                {meta}
                              </span>
                            ) : null}
                            <HighlightedSnippet text={hit.snippet} query={trimmed} />
                            {segmentTime ? (
                              <span className="text-[11px] tabular-nums text-muted-foreground/80">
                                {segmentTime}
                              </span>
                            ) : null}
                          </button>
                        </li>
                      );
                    })}
                  </ul>
                </>
              )}
            </div>
          </div>
        ) : (
          children
        )}
      </div>

      <div className="relative mt-0 shrink-0 border-t py-2 pb-2.5">
        {searchOpen ? (
          <div className="pointer-events-none absolute inset-x-0 bottom-full z-10 mb-2 flex justify-stretch">
            <div
              className={cn(
                floatingSearchShellClass,
                "pointer-events-auto w-full",
              )}
              role="search"
              aria-label="Search meeting transcripts"
            >
              <Input
                ref={inputRef}
                value={query}
                onChange={(e) => setQuery(e.target.value)}
                onKeyDown={onKeyDown}
                placeholder="Search transcripts…"
                className={cn(
                  "h-auto min-w-0 flex-1 rounded-none border-0 bg-transparent",
                  "px-3 py-0 text-sm shadow-none focus-visible:ring-0",
                )}
                aria-label="Search meeting transcripts"
              />
              <span
                className="w-px shrink-0 self-stretch bg-border/80"
                aria-hidden
              />
              <div className="flex shrink-0 items-center px-1">
                <Button
                  type="button"
                  variant="ghost"
                  size="icon-xs"
                  className="text-muted-foreground hover:text-foreground"
                  aria-label="Close search"
                  onClick={closeSearch}
                >
                  <X aria-hidden />
                </Button>
              </div>
            </div>
          </div>
        ) : null}

        <div className="flex items-center gap-1.5">
          <AppTooltip
            label={searchOpen ? "Close search" : "Search transcripts"}
          >
            <Button
              type="button"
              variant="outline"
              size="icon-sm"
              className={cn(
                "shrink-0",
                pipelineToolbarClasses.paneToolbarActionChip,
                searchOpen && "ring-1 ring-border/80 dark:ring-white/25",
              )}
              aria-label={searchOpen ? "Close search" : "Search transcripts"}
              aria-expanded={searchOpen}
              aria-pressed={searchOpen}
              onClick={() => {
                if (searchOpen) closeSearch();
                else onSearchOpenChange(true);
              }}
            >
              <Search aria-hidden strokeWidth={2} />
            </Button>
          </AppTooltip>
          <div className="min-w-0 flex-1">{footerAction}</div>
        </div>
      </div>
    </div>
  );
}
