import { formatMeetingDate } from "./meetingTypes";

/** Short label for the header meeting chip (from epoch ms). */
export function formatMeetingChipLabel(ms: number): string {
  return formatMeetingDate(ms);
}

export function formatSegmentCount(
  outbound: number,
  inbound: number,
): string {
  const total = outbound + inbound;
  if (total <= 0) return "";
  return total === 1 ? "1 segment" : `${total} segments`;
}

const AUTO_TITLE_PATTERNS = [
  /^\d{1,2}:\d{2}$/,
  /^[A-Za-z]{3} \d{1,2}, \d{2}:\d{2}$/,
  /^[A-Za-z]{3} \d{1,2}, \d{4}, \d{2}:\d{2}$/,
  /^[A-Za-z]{3} \d{1,2}, \d{4}/,
  /^[A-Za-z]{3} \d{1,2}, \d{4} ·/,
];

export function isAutoGeneratedMeetingTitle(title: string): boolean {
  const trimmed = title.trim();
  return AUTO_TITLE_PATTERNS.some((p) => p.test(trimmed));
}

/** Chip shows a short date/time for auto titles; custom names stay as-is. */
export function meetingChipDisplayTitle(meeting: {
  title: string;
  startedAtMs: number;
}): string {
  const short = formatMeetingChipLabel(meeting.startedAtMs);
  if (isAutoGeneratedMeetingTitle(meeting.title)) {
    return short;
  }
  return meeting.title;
}

/** Detail page h1 — avoids duplicating raw auto time as both title and subtitle. */
export function meetingDetailDisplayTitle(meeting: {
  title: string;
  startedAtMs: number;
}): string {
  if (!isAutoGeneratedMeetingTitle(meeting.title)) {
    return meeting.title;
  }
  const d = new Date(meeting.startedAtMs);
  const now = new Date();
  const sameDay =
    d.getFullYear() === now.getFullYear() &&
    d.getMonth() === now.getMonth() &&
    d.getDate() === now.getDate();
  if (sameDay) {
    return "Meeting today";
  }
  return `Meeting on ${d.toLocaleDateString([], {
    month: "short",
    day: "numeric",
    year: d.getFullYear() !== now.getFullYear() ? "numeric" : undefined,
  })}`;
}

function formatDurationMs(ms: number): string {
  const totalMin = Math.max(1, Math.round(ms / 60_000));
  if (totalMin < 60) {
    return totalMin === 1 ? "1 min" : `${totalMin} min`;
  }
  const hours = Math.floor(totalMin / 60);
  const mins = totalMin % 60;
  if (mins === 0) {
    return hours === 1 ? "1 hr" : `${hours} hr`;
  }
  return `${hours} hr ${mins} min`;
}

/** Start time for the detail header chip (e.g. `07:34 PM`). */
export function formatMeetingDetailChipTime(startedAtMs: number): string {
  return new Date(startedAtMs).toLocaleTimeString([], {
    hour: "2-digit",
    minute: "2-digit",
  });
}

/** Duration cell for the detail header chip; null when unknown. */
export function formatMeetingDetailChipDuration(meeting: {
  startedAtMs: number;
  endedAtMs: number | null;
}): string | null {
  if (meeting.endedAtMs == null || meeting.endedAtMs <= meeting.startedAtMs) {
    return null;
  }
  return formatDurationMs(meeting.endedAtMs - meeting.startedAtMs);
}

/**
* Second line under the detail header title — compact visible meta.
* Example: `Jul 26 · 3 min · VI → EN` (omit duration while live / unknown).
*/
export function formatMeetingDetailChipMeta(meeting: {
  title: string;
  myLanguage: string;
  meetingLanguage: string;
  startedAtMs: number;
  endedAtMs: number | null;
  sessionMode?: string | null;
}): string {
  const started = new Date(meeting.startedAtMs);
  const date = started.toLocaleDateString([], {
    month: "short",
    day: "numeric",
    year:
      started.getFullYear() !== new Date().getFullYear() ? "numeric" : undefined,
  });
  const parts: string[] = [date];
  const duration = formatMeetingDetailChipDuration(meeting);
  if (duration) parts.push(duration);
  if (meeting.sessionMode === "notes") {
    parts.push(meeting.myLanguage.toUpperCase());
  } else {
    parts.push(
      `${meeting.myLanguage.toUpperCase()} → ${meeting.meetingLanguage.toUpperCase()}`,
    );
  }
  return parts.join(" · ");
}

/** Structured lines for the detail header chip tooltip (no Ended status). */
export function formatMeetingDetailChipTooltip(meeting: {
  title: string;
  myLanguage: string;
  meetingLanguage: string;
  startedAtMs: number;
  sessionMode?: string | null;
}): { name: string; when: string; languages: string } {
  const name = meetingDetailDisplayTitle(meeting);
  const started = new Date(meeting.startedAtMs);
  const time = started.toLocaleTimeString([], {
    hour: "2-digit",
    minute: "2-digit",
  });
  const date = started.toLocaleDateString([], {
    month: "short",
    day: "numeric",
    year:
      started.getFullYear() !== new Date().getFullYear() ? "numeric" : undefined,
  });
  const my = meeting.myLanguage.toUpperCase();
  const other = meeting.meetingLanguage.toUpperCase();
  const languages =
    meeting.sessionMode === "notes" ? my : `${my} ↔ ${other}`;
  return {
    name,
    when: `${date} · ${time}`,
    languages,
  };
}

/**
* Inline meta for the compact title row.
* Skips date when the display title already encodes it (auto-generated titles).
*/
export function formatMeetingDetailInlineMeta(meeting: {
  title: string;
  myLanguage: string;
  meetingLanguage: string;
  startedAtMs: number;
  endedAtMs: number | null;
  status: "live" | "ended";
}): string {
  const started = new Date(meeting.startedAtMs);
  const time = started.toLocaleTimeString([], {
    hour: "2-digit",
    minute: "2-digit",
  });
  const langs = `${meeting.myLanguage.toUpperCase()} ↔ ${meeting.meetingLanguage.toUpperCase()}`;
  const status = meeting.status === "live" ? "Live" : "Ended";
  const parts: string[] = [];

  if (isAutoGeneratedMeetingTitle(meeting.title)) {
    parts.push(time);
  } else {
    const date = started.toLocaleDateString([], {
      month: "short",
      day: "numeric",
      year:
        started.getFullYear() !== new Date().getFullYear()
          ? "numeric"
          : undefined,
    });
    parts.push(`${date} · ${time}`);
  }

  parts.push(langs, status);
  if (meeting.endedAtMs != null && meeting.endedAtMs > meeting.startedAtMs) {
    parts.push(formatDurationMs(meeting.endedAtMs - meeting.startedAtMs));
  }
  return parts.join(" · ");
}

export function formatSummaryProgressLabel(phase: string): string {
  switch (phase) {
    case "chunk":
      return "Reading…";
    case "merge":
    case "partial":
      return "Combining…";
    case "generate":
      return "Generating…";
    default:
      return "Working…";
  }
}

export function formatSummaryProgress(
  phase: string,
  current: number,
  total: number,
): string {
  if (phase === "merge" || phase === "partial") {
    return total > 0
      ? `Updating summary (part ${current} of ${total})…`
      : "Combining notes into summary…";
  }
  if (phase === "generate") {
    return "Generating summary…";
  }
  if (phase === "chunk") {
    return `Reading transcript (part ${current} of ${Math.max(1, total)})…`;
  }
  return `Working (${current}/${total})…`;
}

export function formatSummaryError(message: string): string {
  const raw = message.replace(/^Error:\s*/i, "").trim();
  if (raw === "summary_already_running") {
    return "Summary generation is already running for this meeting.";
  }
  if (raw.startsWith("feature_disabled:")) {
    return "This feature is off — enable it in Settings → Intelligence.";
  }
  if (
    raw.includes("No transcript segments to summarize")
    || raw.includes("No meeting transcript segments to summarize")
  ) {
    return "No transcript was captured. Start a new meeting and record speech on at least one column.";
  }
  if (raw.includes("Unsupported summary language")) {
    return "Choose a supported summary language.";
  }
  if (raw.includes("Unknown summary template")) {
    return "Choose a supported summary template.";
  }
  if (raw.includes("End the meeting before generating a summary")) {
    return "End the meeting before generating a summary.";
  }
  if (raw.includes("is not found for API version") || raw.includes("is not supported for generateContent")) {
    return "Summary generation failed: the configured live-translate model cannot be used for summaries. Please restart the app after updating.";
  }
  if (/timeout|timed out|deadline exceeded/i.test(raw)) {
    return "Summary is taking too long. Try again or use a shorter meeting.";
  }
  if (/rate limit|429|too many requests/i.test(raw)) {
    return "Summary is taking too long. Try again or use a shorter meeting.";
  }
  return raw;
}
