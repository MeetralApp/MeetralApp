import { describe, expect, it } from "vitest";

import {
  formatMeetingDetailChipDuration,
  formatMeetingDetailChipMeta,
  formatMeetingDetailChipTime,
  formatMeetingDetailChipTooltip,
  formatMeetingDetailInlineMeta,
  formatSegmentCount,
  formatSummaryError,
  formatSummaryProgress,
  formatSummaryProgressLabel,
  isAutoGeneratedMeetingTitle,
  meetingChipDisplayTitle,
  meetingDetailDisplayTitle,
} from "./meetingDisplay";

describe("formatSegmentCount", () => {
  it("returns empty for zero segments", () => {
    expect(formatSegmentCount(0, 0)).toBe("");
  });

  it("uses singular for one segment", () => {
    expect(formatSegmentCount(1, 0)).toBe("1 segment");
  });

  it("uses plural for multiple segments", () => {
    expect(formatSegmentCount(2, 3)).toBe("5 segments");
  });
});

