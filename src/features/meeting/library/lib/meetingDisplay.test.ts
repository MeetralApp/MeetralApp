describe("formatMeetingDetailChipDuration", () => {
  it("returns null without end", () => {
    expect(
      formatMeetingDetailChipDuration({
        startedAtMs: 1_000,
        endedAtMs: null,
      }),
    ).toBeNull();
  });

  it("formats short duration", () => {
    expect(
      formatMeetingDetailChipDuration({
        startedAtMs: 0,
        endedAtMs: 60_000,
      }),
    ).toBe("1 min");
  });
});

describe("formatMeetingDetailChipMeta", () => {
  it("joins date · duration · language pair", () => {
    const startedAtMs = new Date(2026, 6, 26, 20, 0).getTime();
    const meta = formatMeetingDetailChipMeta({
      title: "Custom title",
      myLanguage: "vi",
      meetingLanguage: "en",
      startedAtMs,
      endedAtMs: startedAtMs + 3 * 60_000,
    });
    expect(meta).toBe("Jul 26 · 3 min · VI → EN");
  });

  it("omits duration when still open", () => {
    const startedAtMs = new Date(2026, 6, 26, 20, 0).getTime();
    const meta = formatMeetingDetailChipMeta({
      title: "Custom title",
      myLanguage: "vi",
      meetingLanguage: "en",
      startedAtMs,
      endedAtMs: null,
    });
    expect(meta).toBe("Jul 26 · VI → EN");
  });

  it("uses single language for notes mode", () => {
    const startedAtMs = new Date(2026, 6, 26, 20, 0).getTime();
    const meta = formatMeetingDetailChipMeta({
      title: "Notes",
      myLanguage: "vi",
      meetingLanguage: "en",
      startedAtMs,
      endedAtMs: startedAtMs + 60_000,
      sessionMode: "notes",
    });
    expect(meta).toBe("Jul 26 · 1 min · VI");
  });
});

describe("formatMeetingDetailChipTooltip", () => {
  it("returns name, when, and languages without Ended", () => {
    const startedAtMs = new Date(2026, 5, 18, 19, 32).getTime();
    const tip = formatMeetingDetailChipTooltip({
      title: "19:32",
      myLanguage: "vi",
      meetingLanguage: "en",
      startedAtMs,
    });
    expect(tip.name).toBe("Meeting on Jun 18");
    expect(tip.when).toMatch(/Jun 18/);
    expect(tip.languages).toBe("VI ↔ EN");
    expect(JSON.stringify(tip)).not.toMatch(/Ended/i);
  });

  it("uses single language for notes mode", () => {
    const tip = formatMeetingDetailChipTooltip({
      title: "Standup",
      myLanguage: "vi",
      meetingLanguage: "en",
      startedAtMs: Date.now(),
      sessionMode: "notes",
    });
    expect(tip.name).toBe("Standup");
    expect(tip.languages).toBe("VI");
  });
});

describe("formatSummaryError", () => {
  it("humanizes empty transcript errors", () => {
    expect(
      formatSummaryError("No transcript segments to summarize"),
    ).toContain("No transcript was captured");
    expect(
      formatSummaryError("No meeting transcript segments to summarize"),
    ).toContain("No transcript was captured");
  });

  it("humanizes timeout and rate limit errors", () => {
    expect(formatSummaryError("request timed out")).toContain(
      "Summary is taking too long",
    );
    expect(formatSummaryError("rate limit exceeded")).toContain(
      "Summary is taking too long",
    );
  });

  it("humanizes feature_disabled IPC guards", () => {
    expect(formatSummaryError("Error: feature_disabled: artifacts")).toContain(
      "Settings → Intelligence",
    );
  });
});

